import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd();
const output=path.join(root,'../qa/motion-smoke');await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1280,height:600},reducedMotion:'no-preference'});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:8107/next/src/motion/preview.html');
await page.waitForFunction(()=>document.body.dataset.ready==='1');await page.evaluate(()=>document.fonts.ready);
await page.getByRole('button',{name:'Attention',exact:true}).click();
const before=await page.locator('.v-motion-view').evaluate(el=>({transform:getComputedStyle(el).transform,opacity:getComputedStyle(el).opacity}));
await page.emulateMedia({reducedMotion:'reduce'});
await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
const after=await page.locator('.v-motion-view').evaluate(el=>({transform:getComputedStyle(el).transform,opacity:getComputedStyle(el).opacity,policy:window.vigilMotionReview.policy}));
await page.screenshot({path:path.join(output,'attention-reduced.png')});
await page.getByRole('button',{name:'Messages',exact:true}).click();
await page.getByRole('textbox',{name:'Message',exact:true}).fill('Preserved local draft');
await page.emulateMedia({reducedMotion:'no-preference'});
await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
const draft=await page.getByRole('textbox',{name:'Message',exact:true}).inputValue();
await page.screenshot({path:path.join(output,'messages.png')});
const dimensions=await page.evaluate(()=>({width:innerWidth,height:innerHeight,scrollWidth:document.documentElement.scrollWidth,scrollHeight:document.documentElement.scrollHeight}));
const report={before,after,draft,dimensions,errors};await fs.writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
await browser.close();
if(errors.length||draft!=='Preserved local draft'||after.transform!=='none'||dimensions.scrollWidth>1280||dimensions.scrollHeight>600)process.exitCode=1;
